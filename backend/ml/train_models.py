from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import csv,joblib
from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score,precision_score,recall_score,f1_score,classification_report,confusion_matrix
from app.services.nlp import preprocess
ROOT=Path(__file__).resolve().parents[2]
with (ROOT/'data'/'noise_complaints.csv').open(encoding='utf-8',newline='') as f: data=list(csv.DictReader(f))
X=[preprocess(r['text']) for r in data]; y=[r['noise_source'] for r in data]
xt,xv,yt,yv=train_test_split(X,y,test_size=.2,random_state=42,stratify=y)
vec=TfidfVectorizer(ngram_range=(1,2)); a=vec.fit_transform(xt); b=vec.transform(xv)
model=LogisticRegression(max_iter=1000,class_weight='balanced').fit(a,yt); pred=model.predict(b)
(ROOT/'models').mkdir(exist_ok=True); joblib.dump(model,ROOT/'models'/'noise_source_model.pkl');joblib.dump(vec,ROOT/'models'/'tfidf_vectorizer.pkl')
m={'Accuracy':accuracy_score(yv,pred),'Precision macro':precision_score(yv,pred,average='macro',zero_division=0),'Recall macro':recall_score(yv,pred,average='macro',zero_division=0),'F1 macro':f1_score(yv,pred,average='macro',zero_division=0)}
out='# Model results\n\nGenerated by `python ml/train_models.py`; stratified 80/20 split, seed 42.\n\n'+'\n'.join(f'- {k}: {v:.3f}' for k,v in m.items())+'\n\n## Per-class metrics\n\n```text\n'+classification_report(yv,pred,zero_division=0)+'\n```\n\n## Confusion matrix\n\n```text\n'+str(confusion_matrix(yv,pred,labels=model.classes_))+'\n```\n'
(ROOT/'docs'/'model-results.md').write_text(out);print(out)
